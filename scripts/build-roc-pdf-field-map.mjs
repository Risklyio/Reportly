/**
 * Build ROC PDF field map at deploy time (not in serverless runtime).
 */
import fs from "node:fs";
import path from "node:path";
import { buildFieldMapFromPdfPath } from "./roc-pdf-locate.mjs";
import {
  getPublicRocTemplatePath,
  ROC_TEMPLATE_FILENAME,
} from "./roc-template.mjs";

const OUT_JSON = path.join(process.cwd(), "data", "roc-pdf-field-map.json");
const OUT_TS = path.join(
  process.cwd(),
  "lib",
  "export",
  "roc-pdf-field-map.generated.ts"
);

function sanitizeEntries(entries) {
  return entries.map((entry) => {
    const { printedPage, ...rest } = entry;
    return printedPage != null ? { ...rest, printedPage } : rest;
  });
}

function writeGeneratedTs(entries, generatedAt) {
  const body = `// Auto-generated by scripts/build-roc-pdf-field-map.mjs — do not edit.
import type { RocPdfFieldEntry } from "./roc-pdf-types";

export const ROC_PDF_FIELD_MAP_GENERATED_AT = ${JSON.stringify(generatedAt)};

export const ROC_PDF_FIELD_MAP_ENTRIES: RocPdfFieldEntry[] = ${JSON.stringify(entries, null, 2)};
`;
  fs.mkdirSync(path.dirname(OUT_TS), { recursive: true });
  fs.writeFileSync(OUT_TS, body, "utf8");
}

async function main() {
  const pdfPath = getPublicRocTemplatePath();
  if (!fs.existsSync(pdfPath)) {
    console.warn(
      `Skipping ROC field map build — template not found at ${pdfPath}. ` +
        `Run npm run setup-roc-template or set ROC_TEMPLATE_URL before deploy.`
    );
    return;
  }

  const entries = await buildFieldMapFromPdfPath(pdfPath);
  const generatedAt = new Date().toISOString();
  const output = {
    version: ROC_TEMPLATE_FILENAME,
    template: ROC_TEMPLATE_FILENAME,
    generatedAt,
    pageHeight: 792,
    entries,
  };

  fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
  const sanitized = sanitizeEntries(entries);
  fs.writeFileSync(
    OUT_JSON,
    JSON.stringify({ ...output, entries: sanitized }, null, 2),
    "utf8"
  );
  writeGeneratedTs(sanitized, generatedAt);

  console.log(`Wrote ${entries.length} field entries → ${OUT_JSON}`);
  console.log(`Wrote bundled map → ${OUT_TS}`);

  if (entries.length === 0) {
    console.error(
      "ROC field map build produced 0 entries. Check that the official template " +
        "is the PCI DSS v4.0.1 ROC PDF and re-run npm run build-roc-pdf-map."
    );
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
